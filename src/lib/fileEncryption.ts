/**
 * fileEncryption.ts — Hardware-accelerated WebCrypto AES-256-GCM file encryption.
 *
 * Provides client-side authenticated 256-bit AES encryption with PBKDF2 key derivation.
 * Works natively in 100% of modern browser engines with zero external WASM or script downloads.
 */

export interface EncryptedVaultPayload {
  magic: string; // 'CZ25'
  salt: Uint8Array;
  iv: Uint8Array;
  ciphertext: Uint8Array;
}

/**
 * Encrypt arbitrary byte data with AES-256-GCM and PBKDF2 (100,000 iterations).
 * Format: [CZ25 (4B)][Salt (16B)][IV (12B)][Ciphertext + GCM Tag (16B)]
 */
export async function encryptFileAesGcm(
  bytes: Uint8Array,
  passphrase: string,
): Promise<Uint8Array> {
  if (!passphrase) {
    throw new Error("Password cannot be empty.");
  }

  const salt = crypto.getRandomValues(new Uint8Array(16));
  const iv = crypto.getRandomValues(new Uint8Array(12));

  const keyMaterial = await crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(passphrase),
    { name: "PBKDF2" },
    false,
    ["deriveKey"],
  );

  const key = await crypto.subtle.deriveKey(
    {
      name: "PBKDF2",
      salt: salt as BufferSource,
      iterations: 100000,
      hash: "SHA-256",
    },
    keyMaterial,
    { name: "AES-GCM", length: 256 },
    false,
    ["encrypt"],
  );

  const cipherBuffer = await crypto.subtle.encrypt(
    { name: "AES-GCM", iv: iv as BufferSource },
    key,
    bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) as BufferSource,
  );

  const magic = new TextEncoder().encode("CZ25");
  const result = new Uint8Array(4 + 16 + 12 + cipherBuffer.byteLength);
  result.set(magic, 0);
  result.set(salt, 4);
  result.set(iv, 20);
  result.set(new Uint8Array(cipherBuffer), 32);

  return result;
}

/**
 * Decrypt an AES-256-GCM payload generated by encryptFileAesGcm.
 */
export async function decryptFileAesGcm(
  encryptedBytes: Uint8Array,
  passphrase: string,
): Promise<Uint8Array> {
  if (encryptedBytes.length < 4 + 16 + 12 + 16) {
    throw new Error("Invalid encrypted payload: file is too small or truncated.");
  }

  const magic = new TextDecoder().decode(encryptedBytes.subarray(0, 4));
  if (magic !== "CZ25") {
    throw new Error("Invalid file header: not a CompressZ AES-256 encrypted payload.");
  }

  const salt = new Uint8Array(
    encryptedBytes.buffer.slice(
      encryptedBytes.byteOffset + 4,
      encryptedBytes.byteOffset + 20,
    ),
  );
  const iv = new Uint8Array(
    encryptedBytes.buffer.slice(
      encryptedBytes.byteOffset + 20,
      encryptedBytes.byteOffset + 32,
    ),
  );
  const ciphertext = new Uint8Array(
    encryptedBytes.buffer.slice(
      encryptedBytes.byteOffset + 32,
      encryptedBytes.byteOffset + encryptedBytes.byteLength,
    ),
  );

  const keyMaterial = await crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(passphrase),
    { name: "PBKDF2" },
    false,
    ["deriveKey"],
  );

  const key = await crypto.subtle.deriveKey(
    {
      name: "PBKDF2",
      salt: salt as BufferSource,
      iterations: 100000,
      hash: "SHA-256",
    },
    keyMaterial,
    { name: "AES-GCM", length: 256 },
    false,
    ["decrypt"],
  );

  try {
    const plainBuffer = await crypto.subtle.decrypt(
      { name: "AES-GCM", iv: iv as BufferSource },
      key,
      ciphertext as BufferSource,
    );
    return new Uint8Array(plainBuffer);
  } catch {
    throw new Error("Decryption failed: incorrect password or corrupted ciphertext.");
  }
}
